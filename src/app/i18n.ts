export type Key = keyof Dict;
const dicts: Record<Lang, Dict> = { fr, en };

let current: Lang = (() => {
  try {
    const saved = localStorage.getItem('kayit:lang');
    if (saved === 'fr' || saved === 'en') return saved;
  } catch {
    /* ignore */
  }
  return typeof navigator !== 'undefined' && navigator.language?.startsWith('en') ? 'en' : 'fr';
})();

export function setLang(l: Lang): void {
  current = l;
  try {
    localStorage.setItem('kayit:lang', l);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = l;
}

export function lang(): Lang {
  return current;
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const s = dicts[current][key] ?? dicts.fr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

export function fmtDate(sec: number, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'short', year: 'numeric' }): string {
  return new Date(sec * 1000).toLocaleDateString(current === 'fr' ? 'fr-SN' : 'en-GB', opts);
}
